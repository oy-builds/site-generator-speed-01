/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** The characters that can open an inline construct; the scanner jumps between them instead of stepping per char. */
const SPECIAL_RE = /[\\`*[]/g;

/**
 * `s` rendered inline; `link(target)` is a link's href. Plain characters accumulate into a run that is escaped in
 * one call when a construct interrupts it, instead of one escape call per character. (SPECIAL_RE's lastIndex is
 * assigned before every exec, so sharing it across recursive calls is safe.)
 */
function inline(s, link) {
  // A string with no construct opener at all renders as its own escaping.
  SPECIAL_RE.lastIndex = 0;
  if (SPECIAL_RE.exec(s) === null) return esc(s);
  const parts = [];
  let run = 0;
  let i = 0;
  const n = s.length;
  while (i < n) {
    SPECIAL_RE.lastIndex = i;
    const hit = SPECIAL_RE.exec(s);
    i = hit === null ? n : hit.index;
    if (i >= n) break;
    const c = s[i];
    if (c === '\\' && i + 1 < n && ESCAPABLE.has(s[i + 1])) {
      if (i > run) parts.push(esc(s.slice(run, i)));
      parts.push(esc(s[i + 1]));
      i += 2;
      run = i;
      continue;
    }
    if (c === '`') {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        if (i > run) parts.push(esc(s.slice(run, i)));
        parts.push('<code>', esc(s.slice(i + 1, j)), '</code>');
        i = j + 1;
        run = i;
        continue;
      }
      i++;
      continue;
    }
    if (c === '*') {
      if (s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          if (i > run) parts.push(esc(s.slice(run, i)));
          parts.push('<strong>', inline(s.slice(i + 2, j), link), '</strong>');
          i = j + 2;
          run = i;
          continue;
        }
        i += 2;
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        if (i > run) parts.push(esc(s.slice(run, i)));
        parts.push('<em>', inline(s.slice(i + 1, j), link), '</em>');
        i = j + 1;
        run = i;
        continue;
      }
      i++;
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', i + 1);
      const m = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m === -1 ? '' : s.slice(k + 2, m);
      let bad = target === '';
      for (let q = 0; !bad && q < target.length; q++) if (isWsCode(target.charCodeAt(q))) bad = true;
      if (!bad) {
        if (i > run) parts.push(esc(s.slice(run, i)));
        parts.push('<a href="', esc(link(target)), '">', inline(s.slice(i + 1, k), link), '</a>');
        i = m + 1;
        run = i;
        continue;
      }
      i++;
      continue;
    }
    i++;
  }
  if (n > run) parts.push(esc(s.slice(run, n)));
  return parts.join('');
}

/** A line with spaces and tabs at either end dropped. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b) {
    const c = line.charCodeAt(a);
    if (c === 32 || c === 9) a++;
    else break;
  }
  while (b > a) {
    const c = line.charCodeAt(b - 1);
    if (c === 32 || c === 9) b--;
    else break;
  }
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

/** A fence opening line's language, or null: three backticks, language characters, then spaces or tabs only. */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let j = 3;
  while (j < line.length) {
    const c = line.charCodeAt(j);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) j++;
    else break;
  }
  const lang = line.slice(3, j);
  while (j < line.length) {
    const c = line.charCodeAt(j);
    if (c === 32 || c === 9) j++;
    else return null;
  }
  return lang;
}

/** Whether `line` closes a fence: three backticks, then spaces or tabs only. */
function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let j = 3; j < line.length; j++) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's level and text, or null: 1 to 6 #, at least one space or tab, then text (never empty). */
function headingOf(line) {
  // A line holding U+2028 or U+2029 can never match the reference's heading pattern (its "." stops there).
  if (line.includes('\u2028') || line.includes('\u2029')) return null;
  let h = 0;
  while (h < line.length && line.charCodeAt(h) === 35) h++;
  if (h === 0 || h > 6) return null;
  if (h === line.length) return null;
  const c = line.charCodeAt(h);
  if (c !== 32 && c !== 9) return null;
  const text = trimLine(line.slice(h));
  return text === '' ? null : { depth: h, text };
}

/** Whether `line` is a thematic break: --- or ***, then spaces or tabs only. */
function isBreak(line) {
  let b = line.length;
  while (b > 0) {
    const c = line.charCodeAt(b - 1);
    if (c === 32 || c === 9) b--;
    else break;
  }
  if (b !== 3) return false;
  const a = line.charCodeAt(0);
  return a === line.charCodeAt(1) && a === line.charCodeAt(2) && (a === 45 || a === 42);
}

/** Whether `line` ends a paragraph: blank, a fence, a heading or a thematic break (dispatched on its first char). */
function endsParagraph(line) {
  const c = line.charCodeAt(0);
  if (c === 96) return fenceLang(line) !== null;
  if (c === 35) return headingOf(line) !== null;
  if (c === 45 || c === 42) return isBreak(line);
  if (c === 32 || c === 9 || line.length === 0) return isBlankLine(line);
  return false;
}

/** A list line's kind: { ordered, start, text } for a bullet or numbered item line, else null. */
function listItem(line) {
  if (line.includes('\u2028') || line.includes('\u2029')) return null; // the reference's item patterns stop there too
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return { ordered: false, start: 1, text: line.slice(2) };
  if (c >= 48 && c <= 57) {
    let d = 0;
    while (d < line.length) {
      const cc = line.charCodeAt(d);
      if (cc >= 48 && cc <= 57) d++;
      else break;
    }
    if (d <= 9 && line.charCodeAt(d) === 46 && line.charCodeAt(d + 1) === 32) {
      return { ordered: true, start: Number(line.slice(0, d)), text: line.slice(d + 2) };
    }
  }
  return null;
}

/** Whether `line` continues a list item: two or more spaces, then a character other than whitespace. */
function isContinuation(line) {
  let j = 0;
  while (j < line.length && line.charCodeAt(j) === 32) j++;
  return j >= 2 && j < line.length && !isWsCode(line.charCodeAt(j));
}

/**
 * `src` rendered in one pass over its lines: its HTML (a "\n" after every block), its table of contents (every
 * level 2 and 3 heading: level, id and its inline HTML) and its excerpt (the first paragraph's inline HTML, or "").
 * `slug` is the build's memoised slugify.
 */
function renderMarkdown(src, link, slug) {
  const lines = src.split('\n');
  const n = lines.length;
  const ids = new Set();
  const parts = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < n) {
    const line = lines[i];
    const c0 = line.charCodeAt(0);
    // A line opening on a space or tab can only be blank or a paragraph (no other block opens there).
    if (c0 === 32 || c0 === 9 || line.length === 0) {
      if (isBlankLine(line)) {
        i++;
        continue;
      }
      const body = [trimLine(line)];
      i++;
      while (i < n && !endsParagraph(lines[i])) {
        body.push(trimLine(lines[i]));
        i++;
      }
      const html = inline(body.join('\n'), link);
      if (excerpt === null) excerpt = html;
      parts.push(`<p>${html}</p>\n`);
      continue;
    }
    const lang = c0 === 96 ? fenceLang(line) : null;
    if (lang !== null) {
      let block = lang === '' ? '<pre><code>' : `<pre><code class="language-${esc(lang)}">`;
      i++;
      while (i < n && !isFenceClose(lines[i])) {
        block += esc(lines[i]) + '\n';
        i++;
      }
      i++;
      parts.push(block + '</code></pre>\n');
      continue;
    }
    const heading = c0 === 35 ? headingOf(line) : null;
    if (heading !== null) {
      const id = uniqueSlug(slug(heading.text), ids);
      const html = inline(heading.text, link);
      parts.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if ((c0 === 45 || c0 === 42) && isBreak(line)) {
      parts.push('<hr>\n');
      i++;
      continue;
    }
    if (c0 === 62) { // '>'
      const kept = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        let l = lines[i];
        l = l.length > 1 && l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1);
        l = trimLine(l);
        if (l !== '') kept.push(l);
        i++;
      }
      parts.push(kept.length === 0 ? '<blockquote>\n</blockquote>\n' : `<blockquote>\n<p>${inline(kept.join('\n'), link)}</p>\n</blockquote>\n`);
      continue;
    }
    const item = c0 === 45 || c0 === 42 || (c0 >= 48 && c0 <= 57) ? listItem(line) : null;
    if (item !== null) {
      const ordered = item.ordered;
      const items = [];
      while (i < n) {
        const m = listItem(lines[i]);
        if (m !== null && m.ordered === ordered) {
          items.push([trimLine(m.text)]);
          i++;
        } else if (items.length > 0 && isContinuation(lines[i])) {
          items[items.length - 1].push(trimLine(lines[i]));
          i++;
        } else break;
      }
      const tag = ordered ? 'ol' : 'ul';
      let block = (ordered && item.start !== 1 ? `<ol start="${item.start}">` : `<${tag}>`) + '\n';
      for (const it of items) block += `<li>${inline(it.join('\n'), link)}</li>\n`;
      parts.push(block + `</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) {
      body.push(trimLine(lines[i]));
      i++;
    }
    const html = inline(body.join('\n'), link);
    if (excerpt === null) excerpt = html;
    parts.push(`<p>${html}</p>\n`);
  }
  return { html: parts.join(''), toc, excerpt: excerpt ?? '' };
}

